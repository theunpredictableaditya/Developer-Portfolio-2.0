// Component
const NavIcon = ({ iconName, color = "black", size = 24, isActive = false }: Props) => {
  const svgMarkup = icons[iconName];
  const iconColor = isActive ? "#fff" : color;

  if (!svgMarkup) return null;

  const svg = svgMarkup
    .replace(/stroke="#ffffff"/g, `stroke="${iconColor}"`)
    .replace(/color="#ffffff"/g, `color="${iconColor}"`);

  return (
    <div
      className="navSvgContainer"
      style={{ color: iconColor, width: size, height: size }}
      dangerouslySetInnerHTML={{ __html: svg }}
    />
  );
};

